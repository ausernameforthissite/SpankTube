package dev.spanktube.upstream;

import org.junit.jupiter.api.Test;
import org.schabi.newpipe.extractor.MediaFormat;
import org.schabi.newpipe.extractor.stream.SubtitlesStream;

import static org.assertj.core.api.Assertions.assertThat;

class NewPipeSubtitleTracksTest {

    @Test
    void convertsTtmlToVttWithoutDroppingHumanTrack() throws Exception {
        SubtitlesStream stream = stream(MediaFormat.TTML, false);

        SubtitleTrack track = NewPipeUpstreamProvider.subtitleTrack(stream, 0);

        assertThat(track).isNotNull();
        assertThat(track.trackId()).isEqualTo("sub-en-0");
        assertThat(track.language()).isEqualTo("en");
        assertThat(track.label()).isEqualTo("English");
        assertThat(track.format()).isEqualTo("vtt");
        assertThat(track.url()).endsWith("fmt=vtt");
        assertThat(track.autoGenerated()).isFalse();
    }

    @Test
    void preservesAutomaticMarker() throws Exception {
        SubtitlesStream stream = stream(MediaFormat.TTML, true);

        SubtitleTrack track = NewPipeUpstreamProvider.subtitleTrack(stream, 0);

        assertThat(track).isNotNull();
        assertThat(track.trackId()).isEqualTo("auto-en-0");
        assertThat(track.label()).isEqualTo("English (auto)");
        assertThat(track.autoGenerated()).isTrue();
    }

    @Test
    void ignoresUnsupportedSubtitleFormat() throws Exception {
        SubtitlesStream stream = stream(MediaFormat.TRANSCRIPT1, false);

        assertThat(NewPipeUpstreamProvider.subtitleTrack(stream, 0)).isNull();
    }

    private static SubtitlesStream stream(MediaFormat format, boolean automatic) throws Exception {
        return new SubtitlesStream.Builder()
                .setContent("https://www.youtube.com/api/timedtext?lang=en&fmt=ttml", true)
                .setMediaFormat(format)
                .setLanguageCode("en")
                .setAutoGenerated(automatic)
                .build();
    }
}
