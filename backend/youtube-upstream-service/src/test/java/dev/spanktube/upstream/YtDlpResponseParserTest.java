package dev.spanktube.upstream;

import org.junit.jupiter.api.Test;
import tools.jackson.databind.ObjectMapper;

import static org.assertj.core.api.Assertions.assertThat;

class YtDlpResponseParserTest {

    private final YtDlpResponseParser parser = new YtDlpResponseParser(new ObjectMapper());

    @Test
    void parsesChannelWithLocalRoutesAndAvatarMetadata() {
        String json = """
                {
                  "id": "UC123",
                  "title": "Test channel",
                  "channel_url": "https://www.youtube.com/@tester",
                  "subscriber_count": 42,
                  "thumbnails": [{"url": "https://i.ytimg.com/avatar.jpg"}],
                  "entries": [
                    {"_type": "url", "ie_key": "Youtube", "id": "abc12345678", "title": "Video"},
                    {"_type": "playlist", "ie_key": "YoutubePlaylist", "id": "PL123", "title": "List"}
                  ]
                }
                """;

        ChannelDetails details = parser.channel(json);

        assertThat(details.avatarUrl()).isEqualTo("https://i.ytimg.com/avatar.jpg");
        assertThat(details.handle()).isEqualTo("tester");
        assertThat(details.videos().getFirst().url()).isEqualTo("/watch?v=abc12345678");
        assertThat(details.videos().getFirst().thumbnailUrl()).isEqualTo("/media/v/abc12345678/thumbnail");
        assertThat(details.playlists().getFirst().url()).isEqualTo("/playlist?list=PL123");
    }

    @Test
    void parsesSearchKindsWithoutUpstreamUrls() {
        String json = """
                {"entries": [
                  {"_type": "url", "ie_key": "Youtube", "id": "abc12345678", "title": "Video"},
                  {"_type": "url", "ie_key": "YoutubeTab", "id": "UC123", "url": "https://www.youtube.com/channel/UC123", "title": "Channel"},
                  {"_type": "url", "ie_key": "YoutubeTab", "id": "PL123", "url": "https://www.youtube.com/playlist?list=PL123", "title": "List"}
                ]}
                """;

        SearchResults results = parser.search(json);

        assertThat(results.items()).extracting(SearchItem::kind)
                .containsExactly("video", "channel", "playlist");
        assertThat(results.items()).extracting(SearchItem::thumbnailUrl)
                .containsExactly("/media/v/abc12345678/thumbnail", "/media/channel/UC123/avatar",
                        "/media/playlist/PL123/thumbnail");
        assertThat(results.items()).allSatisfy(item -> assertThat(item.url()).doesNotContain("youtube.com"));
    }

    @Test
    void keepsAutomaticSubtitlesAfterHumanTracks() {
        String json = """
                {"id":"abc12345678","formats":[{"format_id":"140","url":"https://rr1.googlevideo.com/v",
                  "protocol":"https","acodec":"mp4a.40.2","vcodec":"none"}],
                 "subtitles":{"en":[{"ext":"vtt","url":"https://www.youtube.com/api/timedtext/en"}]},
                 "automatic_captions":{"de":[{"ext":"vtt","url":"https://www.youtube.com/api/timedtext/de"}]}}
                """;

        VideoDetails details = parser.parse(json);

        assertThat(details.subtitles()).hasSize(2);
        assertThat(details.subtitles().getFirst().language()).isEqualTo("en");
        assertThat(details.subtitles().getFirst().label()).isEqualTo("en");
        assertThat(details.subtitles().getFirst().autoGenerated()).isFalse();
        assertThat(details.subtitles().get(1).language()).isEqualTo("de");
        assertThat(details.subtitles().get(1).label()).isEqualTo("de (auto)");
        assertThat(details.subtitles().get(1).autoGenerated()).isTrue();
    }

    @Test
    void readsLiveDashWithoutTreatingManifestAsAMediaFile() {
        String json = """
                {"id":"rFZHOHl-L8A","is_live":true,"formats":[
                  {"format_id":"137","url":"https://manifest.googlevideo.com/api/manifest/dash/id",
                   "protocol":"http_dash_segments","vcodec":"avc1.640028","acodec":"none"}]}
                """;

        VideoDetails details = parser.parse(json);

        assertThat(details.streamType()).isEqualTo("LIVE_STREAM");
        assertThat(details.isLive()).isTrue();
        assertThat(details.liveDashUrl()).isEqualTo("https://manifest.googlevideo.com/api/manifest/dash/id");
        assertThat(details.formats()).isEmpty();
    }

    @Test
    void readsLiveHlsWithoutRequiringDash() {
        String json = """
                {"id":"rFZHOHl-L8A","is_live":true,"formats":[
                  {"format_id":"720p","url":"https://manifest.googlevideo.com/api/manifest/hls_playlist/id",
                   "protocol":"m3u8_native","vcodec":"avc1.640028","acodec":"mp4a.40.2"}]}
                """;

        VideoDetails details = parser.parse(json);

        assertThat(details.isLive()).isTrue();
        assertThat(details.liveDashUrl()).isNull();
        assertThat(details.liveHlsUrl()).isEqualTo("https://manifest.googlevideo.com/api/manifest/hls_playlist/id");
        assertThat(details.formats()).isEmpty();
        assertThat(PublicVideo.from(details).manifestUrl()).isEqualTo("/media/v/rFZHOHl-L8A/live.m3u8");
    }

    @Test
    void readsLegacyCachedTrackMetadata() throws Exception {
        String json = """
                {"videoId":"abc12345678","title":"t","channelId":"UC1","channelName":"c",
                 "formats":[{"formatId":"251","url":"https://rr1.googlevideo.com/a","mimeType":"audio/webm",
                   "codecs":"opus","hasVideo":false,"hasAudio":true}],
                 "subtitles":[{"trackId":"sub-en","language":"en","label":"English","format":"vtt",
                   "url":"https://www.youtube.com/api/timedtext/en"}]}
                """;

        VideoDetails details = new ObjectMapper().readValue(json, VideoDetails.class);
        PublicVideo publicVideo = PublicVideo.from(details);

        assertThat(details.formats().getFirst().trackId()).isEqualTo("251");
        assertThat(publicVideo.formats().getFirst().autoGenerated()).isFalse();
        assertThat(publicVideo.subtitles().getFirst().autoGenerated()).isFalse();
    }
}
