import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.stereotype.Component;
import reactor.netty.http.client.HttpClient;

@Component
class NewPipeUpstreamProvider implements UpstreamProvider {

    private static final Pattern DESCRIPTION_CHAPTER = Pattern.compile(
            "(?i)(?:^|<br\\s*/?>)\\s*(?:<a\\b[^>]*>)?(?:(\\d+):)?(\\d{1,2}):(\\d{2})(?:</a>)?\\s+([^<\\r\\n]+)");

    private final StreamingService service = ServiceList.YouTube;
    private final NewPipePageCodec pages;
    private final EgressProbe egressProbe;

    NewPipeUpstreamProvider(@Qualifier("youtubeHttpClient") HttpClient httpClient,
            NewPipePageCodec pages, ObjectProvider<EgressProbe> egressProbe) {
        NewPipe.init(new ReactorNettyDownloader(httpClient));
        this.pages = pages;
        this.egressProbe = egressProbe.getIfAvailable();
    }

    @Override
    public VideoDetails video(String videoId) {
        if (videoId == null || !videoId.matches("[A-Za-z0-9_-]{11}")) {
            throw new IllegalArgumentException("Invalid videoId");
        }
        return call(() -> {
            StreamInfo info = StreamInfo.getInfo(service, "https://www.youtube.com/watch?v=" + videoId);
            List<StreamFormat> formats = new ArrayList<>();
            info.getVideoOnlyStreams().forEach(stream -> addFormat(formats, videoFormat(stream, true)));
            info.getVideoStreams().forEach(stream -> addFormat(formats, videoFormat(stream, false)));
            info.getAudioStreams().forEach(stream -> addFormat(formats, audioFormat(stream)));
            if (formats.isEmpty()) {
                throw UpstreamException.failed("NewPipe returned no DASH-compatible media formats");
            }
            List<SubtitleTrack> subtitles = new ArrayList<>();
            for (SubtitlesStream stream : info.getSubtitles()) {
                if (stream.isAutoGenerated() || !"vtt".equals(stream.getExtension())) {
                    continue;
                }
                String language = stream.getLanguageTag();
                String normalized = language.toLowerCase(Locale.ROOT).replaceAll("[^a-z0-9_-]", "-");
                subtitles.add(new SubtitleTrack("sub-" + normalized + "-" + subtitles.size(), language,
                        stream.getDisplayLanguageName(), "vtt", stream.getContent()));
            }
            String channelUrl = info.getUploaderUrl();
            List<VideoChapter> chapters = info.getStreamSegments().stream()
                    .map(segment -> new VideoChapter(segment.getTitle(), (long) segment.getStartTimeSeconds()))
                    .toList();
            if (chapters.isEmpty()) {
                chapters = chaptersFromDescription(info.getDescription() == null ? null : info.getDescription().content());
            }
            return new VideoDetails(info.getId(), info.getName(),
                    info.getDescription() == null ? null : info.getDescription().content(), channelId(channelUrl),
                    info.getUploaderName(), handle(channelUrl), customPath(channelUrl),
                    bestImage(info.getUploaderAvatars()), number(info.getUploaderSubscriberCount()),
                    number(info.getDuration()), number(info.getViewCount()), number(info.getLikeCount()),
                    info.getUploadDate() == null ? null : info.getUploadDate().getInstant().toString(),
                    bestImage(info.getThumbnails()), List.copyOf(formats), List.copyOf(subtitles), chapters);
        });
    }

    @Override
    public SearchResults search(String query, String type, String cursor) {
        if (query == null || query.isBlank() || query.length() > 200) {
            throw new IllegalArgumentException("Search query must contain 1-200 characters");
        }
        String filter = switch (type == null ? "videos" : type) {
            case "videos", "channels", "playlists" -> type == null ? "videos" : type;
            default -> throw new IllegalArgumentException("Unknown search type");
        };
        return call(() -> {
            var handler = service.getSearchQHFactory().fromQuery(query, List.of(filter), null);
            Page page = pages.decode(cursor);
            if (page == null) {
                SearchInfo info = SearchInfo.getInfo(service, handler);
                return new SearchResults(items(info.getRelatedItems()), pages.encode(info.getNextPage()));
            }
            InfoItemsPage<InfoItem> info = SearchInfo.getMoreItems(service, handler, page);
            return new SearchResults(items(info.getItems()), pages.encode(info.getNextPage()));
        });
    }

    @Override
    public ChannelDetails channel(String channelId, String cursor) {
        return call(() -> {
            ChannelInfo info = ChannelInfo.getInfo(service, channelUrl(channelId));
            List<SearchItem> videos = List.of();
            String nextCursor = null;
            ListLinkHandler videosTab = tab(info, ChannelTabs.VIDEOS);
            if (videosTab != null) {
                Page page = pages.decode(cursor);
                if (page == null) {
                    ChannelTabInfo tabInfo = ChannelTabInfo.getInfo(service, videosTab);
                    videos = items(tabInfo.getRelatedItems());
                    nextCursor = pages.encode(tabInfo.getNextPage());
                } else {
                    InfoItemsPage<InfoItem> tabInfo = ChannelTabInfo.getMoreItems(service, videosTab, page);
                    videos = items(tabInfo.getItems());
                    nextCursor = pages.encode(tabInfo.getNextPage());
                }
            }
            return new ChannelDetails(info.getId(), info.getName(), handle(info.getUrl()), customPath(info.getUrl()),
                    bestImage(info.getAvatars()), number(info.getSubscriberCount()), videos, List.of(), nextCursor);
        });
    }

    @Override
    public SearchResults channelVideos(String channelId, String cursor) {
        return channelTab(channelId, ChannelTabs.VIDEOS, cursor);
    }

    @Override
    public SearchResults channelPlaylists(String channelId, String cursor) {
        return channelTab(channelId, ChannelTabs.PLAYLISTS, cursor);
    }

    private SearchResults channelTab(String channelId, String tab, String cursor) {
        return call(() -> {
            String url = channelUrl(channelId) + "/" + tab;
            ListLinkHandler handler = new ListLinkHandler(url, url, channelId, List.of(tab), "");
            Page page = pages.decode(cursor);
            if (page == null) {
                ChannelTabInfo info = ChannelTabInfo.getInfo(service, handler);
                return new SearchResults(items(info.getRelatedItems()), pages.encode(info.getNextPage()));
            }
            InfoItemsPage<InfoItem> info = ChannelTabInfo.getMoreItems(service, handler, page);
            return new SearchResults(items(info.getItems()), pages.encode(info.getNextPage()));
        });
    }

    @Override
    public PlaylistDetails playlist(String playlistId, String cursor) {
        if (playlistId == null || !playlistId.matches("[A-Za-z0-9_-]+")) {
            throw new IllegalArgumentException("Invalid playlistId");
        }
        return call(() -> {
            String url = "https://www.youtube.com/playlist?list=" + playlistId;
            PlaylistInfo info = PlaylistInfo.getInfo(service, url);
            Page page = pages.decode(cursor);
            List<SearchItem> items;
            String nextCursor;
            if (page == null) {
                items = items(info.getRelatedItems());
                nextCursor = pages.encode(info.getNextPage());
            } else {
                InfoItemsPage<StreamInfoItem> next = PlaylistInfo.getMoreItems(service, url, page);
                items = items(next.getItems());
                nextCursor = pages.encode(next.getNextPage());
            }
            String thumbnail = bestImage(info.getThumbnails());
            if (thumbnail == null && !info.getRelatedItems().isEmpty()) {
                thumbnail = bestImage(info.getRelatedItems().getFirst().getThumbnails());
            }
            String channelUrl = info.getUploaderUrl();
            return new PlaylistDetails(info.getId(), info.getName(), channelId(channelUrl), info.getUploaderName(),
                    bestImage(info.getUploaderAvatars()), handle(channelUrl), customPath(channelUrl), null,
                    items, nextCursor, thumbnail, info.getStreamCount(), info.getRelatedItems().size());
        });
    }

    private List<SearchItem> items(List<? extends InfoItem> source) {
        return source.stream().map(NewPipeUpstreamProvider::item)
                .filter(item -> item != null).toList();
    }

    private static SearchItem item(InfoItem info) {
        if (info instanceof StreamInfoItem stream) {
            String id = queryParameter(stream.getUrl(), "v");
            if (id == null || !id.matches("[A-Za-z0-9_-]{11}")) {
                return null;
            }
            return new SearchItem("video", id, stream.getName(), "/watch?v=" + id,
                    "/media/v/" + id + "/thumbnail", stream.getUploaderName(), number(stream.getDuration()), null,
                    number(stream.getViewCount()), stream.getUploadDate() == null ? null
                            : stream.getUploadDate().getInstant().toString());
        }
        if (info instanceof ChannelInfoItem channel) {
            String id = channelId(channel.getUrl());
            if (id == null || !id.matches("@?[A-Za-z0-9_.-]+")) {
                return null;
            }
            String route = channelRoute(channel.getUrl(), id);
            String fallback = "/media/channel/" + id + "/avatar";
            return new SearchItem("channel", id, channel.getName(), route,
                    MediaLinks.thumbnail(bestImage(channel.getThumbnails()), fallback), null, null,
                    count(channel.getStreamCount()), null, null);
        }
        if (info instanceof PlaylistInfoItem playlist) {
            String id = queryParameter(playlist.getUrl(), "list");
            if (id == null || !id.matches("[A-Za-z0-9_-]+")) {
                return null;
            }
            String fallback = "/media/playlist/" + id + "/thumbnail";
            return new SearchItem("playlist", id, playlist.getName(), "/playlist?list=" + id,
                    MediaLinks.thumbnail(bestImage(playlist.getThumbnails()), fallback), playlist.getUploaderName(),
                    null, count(playlist.getStreamCount()), null, null);
        }
        return null;
    }

    private static StreamFormat videoFormat(VideoStream stream, boolean videoOnly) {
        String formatId = stream.getItag() > 0 ? Integer.toString(stream.getItag()) : stream.getId();
        if (!supportedFormat(formatId, stream.getContent(), stream.getFormat())) {
            return null;
        }
        ItagItem itag = stream.getItagItem();
        String codec = stream.getCodec() == null && itag != null ? itag.getCodec() : stream.getCodec();
        return new StreamFormat(formatId, stream.getContent(), stream.getFormat().getMimeType(),
                codec == null ? "unknown" : codec, positiveInt(stream.getWidth()), positiveInt(stream.getHeight()),
                stream.getFps() > 0 ? (double) stream.getFps() : null, positiveLong(stream.getBitrate()), null,
                itag != null && itag.getContentLength() > 0 ? itag.getContentLength() : null,
                true, !videoOnly, range(stream.getInitStart(), stream.getInitEnd()),
                range(stream.getIndexStart(), stream.getIndexEnd()));
    }

    private static StreamFormat audioFormat(AudioStream stream) {
        String formatId = stream.getItag() > 0 ? Integer.toString(stream.getItag()) : stream.getId();
        if (!supportedFormat(formatId, stream.getContent(), stream.getFormat())) {
            return null;
        }
        ItagItem itag = stream.getItagItem();
        String codec = stream.getCodec() == null && itag != null ? itag.getCodec() : stream.getCodec();
        return new StreamFormat(formatId, stream.getContent(), stream.getFormat().getMimeType(),
                codec == null ? "unknown" : codec, null, null, null,
                positiveLong(stream.getAverageBitrate() > 0 ? stream.getAverageBitrate() : stream.getBitrate()),
                itag != null && itag.getSampleRate() > 0 ? itag.getSampleRate() : null,
                itag != null && itag.getContentLength() > 0 ? itag.getContentLength() : null,
                false, true, range(stream.getInitStart(), stream.getInitEnd()),
                range(stream.getIndexStart(), stream.getIndexEnd()));
    }

    private static boolean supportedFormat(String formatId, String content, MediaFormat format) {
        return formatId != null && formatId.matches("[A-Za-z0-9._-]+")
                && content != null && content.startsWith("https://") && !content.contains("m3u8") && format != null;
    }

    private static void addFormat(List<StreamFormat> formats, StreamFormat format) {
        if (format != null) {
            formats.add(format);
        }
    }

    private static String range(int start, int end) {
        return start >= 0 && end > start ? start + "-" + end : null;
    }

    static List<VideoChapter> chaptersFromDescription(String description) {
        if (description == null || description.isBlank()) {
            return List.of();
        }
        List<VideoChapter> chapters = new ArrayList<>();
        Matcher matcher = DESCRIPTION_CHAPTER.matcher(description);
        while (matcher.find()) {
            long hours = matcher.group(1) == null ? 0 : Long.parseLong(matcher.group(1));
            long minutes = Long.parseLong(matcher.group(2));
            long seconds = Long.parseLong(matcher.group(3));
            String title = matcher.group(4).trim();
            if (!title.isEmpty()) {
                chapters.add(new VideoChapter(title, hours * 3600 + minutes * 60 + seconds));
            }
        }
        return List.copyOf(chapters);
    }

    private static ListLinkHandler tab(ChannelInfo info, String name) {
        return info.getTabs().stream().filter(tab -> tab.getContentFilters().contains(name)).findFirst().orElse(null);
    }

    private static String bestImage(List<Image> images) {
        if (images == null) {
            return null;
        }
        return images.stream().max(Comparator.comparingInt(Image::getHeight)).map(Image::getUrl).orElse(null);
    }

    private static String channelUrl(String channelId) {
        if (channelId == null || !channelId.matches("@?[A-Za-z0-9_.-]+")) {
            throw new IllegalArgumentException("Invalid channelId");
        }
        return "https://www.youtube.com/" + (channelId.startsWith("@") ? channelId
                : channelId.startsWith("UC") ? "channel/" + channelId : "c/" + channelId);
    }

    private static String channelRoute(String url, String id) {
        String path = URI.create(url).getPath();
        return path.startsWith("/@") || path.startsWith("/c/") ? path : "/channel/" + id;
    }

    private static String channelId(String url) {
        if (url == null) {
            return null;
        }
        String path = URI.create(url).getPath();
        if (path == null || path.isBlank()) {
            return null;
        }
        if (path.startsWith("/channel/")) {
            return path.substring("/channel/".length()).replaceAll("/.*$", "");
        }
        if (path.startsWith("/@")) {
            return path.substring(1).replaceAll("/.*$", "");
        }
        String[] parts = path.split("/");
        return parts.length == 0 ? null : parts[parts.length - 1];
    }

    private static String handle(String url) {
        return pathPart(url, "/@");
    }

    private static String customPath(String url) {
        return pathPart(url, "/c/");
    }

    private static String pathPart(String url, String marker) {
        if (url == null) {
            return null;
        }
        String path = URI.create(url).getPath();
        if (path == null || !path.startsWith(marker)) {
            return null;
        }
        return path.substring(marker.length()).replaceAll("[^A-Za-z0-9_.-].*$", "");
    }

    private static String queryParameter(String url, String name) {
        if (url == null) {
            return null;
        }
        String query = URI.create(url).getQuery();
        if (query == null) {
            return null;
        }
        for (String part : query.split("&")) {
            int separator = part.indexOf('=');
            if (separator > 0 && part.substring(0, separator).equals(name)) {
                return URLDecoder.decode(part.substring(separator + 1), StandardCharsets.UTF_8);
            }
        }
        return null;
    }

    private static Long number(long value) {
        return value >= 0 ? value : null;
    }

    private static Long positiveLong(long value) {
        return value > 0 ? value : null;
    }

    private static Integer positiveInt(int value) {
        return value > 0 ? value : null;
    }

    private static Integer count(long value) {
        return value < 0 ? null : (int) Math.min(Integer.MAX_VALUE, value);
    }

    private <T> T call(ExtractorCall<T> action) {
        if (egressProbe != null && !egressProbe.isAvailable()) {
            throw UpstreamException.unavailable("YouTube egress is unavailable: " + egressProbe.lastError());
        }
        try {
            return action.get();
        } catch (IllegalArgumentException | UpstreamException error) {
            throw error;
        } catch (Exception error) {
            String message = error.getMessage() == null ? error.getClass().getSimpleName() : error.getMessage();
            String normalized = message.toLowerCase(Locale.ROOT);
            if (normalized.contains("sign in to confirm") || normalized.contains("not a bot")
                    || normalized.contains("po token") || normalized.contains("po_token")
                    || normalized.contains("botguard")) {
                throw UpstreamException.antiBot(message);
            }
            throw UpstreamException.failed("NewPipeExtractor: " + message, error);
        }
    }

    @FunctionalInterface
    private interface ExtractorCall<T> {
        T get() throws Exception;
    }
}
