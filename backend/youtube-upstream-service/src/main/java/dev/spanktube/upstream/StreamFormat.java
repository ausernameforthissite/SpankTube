package dev.spanktube.upstream;

public record StreamFormat(
        String formatId,
        String url,
        String mimeType,
        String codecs,
        Integer width,
        Integer height,
        Double fps,
        Long bitrate,
        Integer audioSampleRate,
        Long contentLength,
        boolean hasVideo,
        boolean hasAudio,
        String initRange,
        String indexRange,
        String trackId,
        String language,
        String label,
        Boolean original,
        Boolean autoGenerated) {

    public StreamFormat(String formatId, String url, String mimeType, String codecs, Integer width, Integer height,
            Double fps, Long bitrate, Integer audioSampleRate, Long contentLength, boolean hasVideo, boolean hasAudio,
            String initRange, String indexRange) {
        this(formatId, url, mimeType, codecs, width, height, fps, bitrate, audioSampleRate, contentLength,
                hasVideo, hasAudio, initRange, indexRange, formatId, null, null, null, false);
    }

    @Override
    public String trackId() {
        return trackId == null ? formatId : trackId;
    }

    public StreamFormat withTrackId(String value) {
        return new StreamFormat(formatId, url, mimeType, codecs, width, height, fps, bitrate, audioSampleRate,
                contentLength, hasVideo, hasAudio, initRange, indexRange, value, language, label, original,
                autoGenerated);
    }
}
