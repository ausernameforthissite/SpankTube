package dev.spanktube.media;

import org.junit.jupiter.api.Test;
import tools.jackson.databind.ObjectMapper;

import static org.assertj.core.api.Assertions.assertThat;

class UpstreamVideoTest {

    @Test
    void readsLegacyCachedTrackMetadata() {
        String json = """
                {"videoId":"H3f-Md1FzDw","durationSeconds":600,
                 "formats":[{"formatId":"137","url":"https://rr1.googlevideo.com/video",
                 "mimeType":"video/mp4","codecs":"avc1.640028","hasVideo":true,"hasAudio":false}],
                 "subtitles":[]}
                """;

        UpstreamVideo video = new ObjectMapper().readValue(json, UpstreamVideo.class);

        assertThat(video.formats().getFirst().autoGenerated()).isFalse();
        assertThat(video.formats().getFirst().trackId()).isEqualTo("137");
    }

    @Test
    void separatesLegacyDuplicateTracksWithoutChangingItags() {
        String json = """
                {"videoId":"H3f-Md1FzDw","formats":[
                  {"formatId":"251","url":"https://rr1.googlevideo.com/a","hasVideo":false,"hasAudio":true},
                  {"formatId":"251","url":"https://rr1.googlevideo.com/b","hasVideo":false,"hasAudio":true}],
                 "subtitles":[]}
                """;

        UpstreamVideo video = new ObjectMapper().readValue(json, UpstreamVideo.class);

        assertThat(video.formats()).extracting(UpstreamVideo.Format::trackId).containsExactly("251", "251-2");
        assertThat(video.formats()).extracting(UpstreamVideo.Format::formatId).containsExactly("251", "251");
    }
}
