package dev.spanktube.media;

import java.util.List;

public record UpstreamVideo(String videoId, Long durationSeconds,
        List<Format> formats, List<Subtitle> subtitles, String streamType, String liveDashUrl, String liveHlsUrl) {

    public UpstreamVideo {
        List<Format> unique = new java.util.ArrayList<>();
        java.util.Set<String> ids = new java.util.HashSet<>();
        for (Format format : formats) {
            String base = format.trackId();
            String candidate = base;
            int suffix = 2;
            while (!ids.add(candidate)) {
                candidate = base + "-" + suffix++;
            }
            unique.add(format.withTrackId(candidate));
        }
        formats = List.copyOf(unique);
        subtitles = List.copyOf(subtitles);
    }

    public UpstreamVideo(String videoId, Long durationSeconds, List<Format> formats, List<Subtitle> subtitles) {
        this(videoId, durationSeconds, formats, subtitles, "VIDEO_STREAM", null, null);
    }

    public UpstreamVideo(String videoId, Long durationSeconds, List<Format> formats, List<Subtitle> subtitles,
            String streamType, String liveDashUrl) {
        this(videoId, durationSeconds, formats, subtitles, streamType, liveDashUrl, null);
    }

    @Override
    public String streamType() {
        return streamType == null ? "VIDEO_STREAM" : streamType;
    }

    public boolean isLive() {
        return "LIVE_STREAM".equals(streamType()) || "AUDIO_LIVE_STREAM".equals(streamType());
    }

    public record Format(String formatId, String url, String mimeType, String codecs,
            Integer width, Integer height, Double fps, Long bitrate, Integer audioSampleRate,
            Long contentLength, boolean hasVideo, boolean hasAudio, String initRange, String indexRange,
            String trackId, String language, String label, Boolean original, Boolean autoGenerated) {

        @Override
        public Boolean autoGenerated() {
            return Boolean.TRUE.equals(autoGenerated);
        }

        public Format(String formatId, String url, String mimeType, String codecs, Integer width, Integer height,
                Double fps, Long bitrate, Integer audioSampleRate, Long contentLength, boolean hasVideo,
                boolean hasAudio, String initRange, String indexRange) {
            this(formatId, url, mimeType, codecs, width, height, fps, bitrate, audioSampleRate, contentLength,
                    hasVideo, hasAudio, initRange, indexRange, formatId, null, null, null, false);
        }

        @Override
        public String trackId() {
            return trackId == null ? formatId : trackId;
        }

        public Format withTrackId(String value) {
            return new Format(formatId, url, mimeType, codecs, width, height, fps, bitrate, audioSampleRate,
                    contentLength, hasVideo, hasAudio, initRange, indexRange, value, language, label, original,
                    autoGenerated);
        }
    }

    public record Subtitle(String trackId, String language, String label, String format, String url,
            boolean autoGenerated) {
        public Subtitle(String trackId, String language, String label, String format, String url) {
            this(trackId, language, label, format, url, false);
        }
    }
}
