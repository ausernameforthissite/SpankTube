package dev.spanktube.media;

import java.nio.ByteBuffer;
import java.nio.charset.StandardCharsets;
import java.time.Duration;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.concurrent.ConcurrentHashMap;

import org.springframework.beans.factory.annotation.Qualifier;
import org.springframework.http.HttpHeaders;
import org.springframework.stereotype.Service;
import org.springframework.web.reactive.function.client.WebClient;
import reactor.core.publisher.Flux;
import reactor.core.publisher.Mono;

@Service
class Mp4IndexService {

    private static final int HEADER_BYTES = 256 * 1024;
    private static final Duration INDEX_CACHE_TTL = Duration.ofMinutes(5);
    private static final int INDEX_CACHE_MAX = 128;

    private final WebClient youtubeClient;
    private final PlaybackLogService playbackLogs;
    private final ConcurrentHashMap<String, CacheEntry> enriched = new ConcurrentHashMap<>();

    Mp4IndexService(@Qualifier("youtubeWebClient") WebClient youtubeClient, PlaybackLogService playbackLogs) {
        this.youtubeClient = youtubeClient;
        this.playbackLogs = playbackLogs;
    }

    Mono<UpstreamVideo> enrich(UpstreamVideo video, String playbackSession) {
        return enrich(video, playbackSession, false);
    }

    Mono<UpstreamVideo> enrich(UpstreamVideo video, String playbackSession, boolean full) {
        String key = video.videoId() + ":" + full;
        long now = System.nanoTime();
        CacheEntry cached = enriched.get(key);
        if (cached != null && cached.expiresAt() > now) {
            return cached.value();
        }
        Mono<UpstreamVideo> shared = load(video, playbackSession, full).cache();
        enriched.put(key, new CacheEntry(shared, now + INDEX_CACHE_TTL.toNanos()));
        while (enriched.size() > INDEX_CACHE_MAX) {
            enriched.remove(enriched.keySet().iterator().next());
        }
        return shared.doFinally(signal -> {
            if (signal != reactor.core.publisher.SignalType.ON_COMPLETE) {
                enriched.remove(key);
            }
        });
    }

    private Mono<UpstreamVideo> load(UpstreamVideo video, String playbackSession, boolean full) {
        List<UpstreamVideo.Format> formats = full ? video.formats() : compactFormats(video.formats());
        playbackLogs.log(video.videoId(), playbackSession, "Чтение MP4-индексов форматов…");
        return Flux.fromIterable(formats)
                .flatMapSequential(format -> enrichFormat(video.videoId(), format, playbackSession), 6)
                .collectList()
                .map(enrichedFormats -> new UpstreamVideo(video.videoId(), video.durationSeconds(), enrichedFormats,
                        video.subtitles(), video.streamType(), video.liveDashUrl(), video.liveHlsUrl()));
    }

    static List<UpstreamVideo.Format> compactFormats(List<UpstreamVideo.Format> source) {
        List<UpstreamVideo.Format> result = new ArrayList<>();
        Map<Integer, UpstreamVideo.Format> videos = new LinkedHashMap<>();
        Map<AudioTrackKey, UpstreamVideo.Format> audio = new LinkedHashMap<>();
        for (UpstreamVideo.Format format : source) {
            if (format.hasVideo() && format.hasAudio()) {
                result.add(format);
            } else if (format.hasVideo()) {
                Integer height = format.height();
                UpstreamVideo.Format previous = videos.get(height);
                if (previous == null) {
                    videos.put(height, format);
                    result.add(format);
                } else {
                    UpstreamVideo.Format preferred = preferredVideo(previous, format);
                    videos.put(height, preferred);
                    if (preferred != previous) {
                        result.set(result.indexOf(previous), preferred);
                    }
                }
            } else if (format.hasAudio()) {
                AudioTrackKey key = new AudioTrackKey(format.mimeType(), format.language(), format.label(),
                        format.original(), format.autoGenerated());
                UpstreamVideo.Format previous = audio.get(key);
                if (previous == null) {
                    audio.put(key, format);
                    result.add(format);
                } else if (bitrate(format) > bitrate(previous)) {
                    audio.put(key, format);
                    result.set(result.indexOf(previous), format);
                }
            }
        }
        return List.copyOf(result);
    }

    private static UpstreamVideo.Format preferredVideo(UpstreamVideo.Format left, UpstreamVideo.Format right) {
        int leftMp4 = left.mimeType() != null && left.mimeType().endsWith("/mp4") ? 1 : 0;
        int rightMp4 = right.mimeType() != null && right.mimeType().endsWith("/mp4") ? 1 : 0;
        if (leftMp4 != rightMp4) {
            return rightMp4 > leftMp4 ? right : left;
        }
        if (bitrate(right) != bitrate(left)) {
            return bitrate(right) > bitrate(left) ? right : left;
        }
        double leftFps = left.fps() == null ? 0 : left.fps();
        double rightFps = right.fps() == null ? 0 : right.fps();
        return rightFps > leftFps ? right : left;
    }

    private static long bitrate(UpstreamVideo.Format format) {
        return format.bitrate() == null ? 0 : format.bitrate();
    }

    private Mono<UpstreamVideo.Format> enrichFormat(String videoId, UpstreamVideo.Format format,
            String playbackSession) {
        if (format.indexRange() != null || format.mimeType() == null || !format.mimeType().endsWith("/mp4")) {
            return Mono.just(format);
        }
        playbackLogs.log(videoId, playbackSession, "Чтение MP4-индекса: формат " + format.formatId());
        return youtubeClient.get()
                .uri(MediaUrlValidator.mediaUrl(format.url()))
                .header(HttpHeaders.RANGE, "bytes=0-" + (HEADER_BYTES - 1))
                .retrieve()
                .bodyToMono(byte[].class)
                .map(bytes -> withIndex(format, bytes))
                .retryWhen(MediaRetry.transientFailures())
                .doOnNext(enriched -> playbackLogs.log(videoId, playbackSession,
                        "MP4-индекс готов: формат " + format.formatId()));
    }

    static UpstreamVideo.Format withIndex(UpstreamVideo.Format format, byte[] bytes) {
        format = withAvcCodec(format, bytes);
        ByteBuffer buffer = ByteBuffer.wrap(bytes);
        int offset = 0;
        while (offset + 8 <= buffer.capacity()) {
            long size = Integer.toUnsignedLong(buffer.getInt(offset));
            String type = new String(bytes, offset + 4, 4, StandardCharsets.ISO_8859_1);
            int headerSize = 8;
            if (size == 1) {
                if (offset + 16 > buffer.capacity()) {
                    break;
                }
                size = buffer.getLong(offset + 8);
                headerSize = 16;
            }
            if (size < headerSize) {
                break;
            }
            if ("sidx".equals(type)) {
                String initRange = offset == 0 ? null : "0-" + (offset - 1);
                String indexRange = offset + "-" + (offset + size - 1);
                return new UpstreamVideo.Format(format.formatId(), format.url(), format.mimeType(), format.codecs(),
                        format.width(), format.height(), format.fps(), format.bitrate(), format.audioSampleRate(),
                        format.contentLength(), format.hasVideo(), format.hasAudio(), initRange, indexRange,
                        format.trackId(), format.language(), format.label(), format.original(), format.autoGenerated());
            }
            if (size == 0 || offset + size > buffer.capacity()) {
                break;
            }
            offset += (int) size;
        }
        return format;
    }

    private static UpstreamVideo.Format withAvcCodec(UpstreamVideo.Format format, byte[] bytes) {
        if (!format.hasVideo() || format.codecs() == null) {
            return format;
        }
        for (int offset = 0; offset + 8 <= bytes.length; offset++) {
            if (bytes[offset] != 'a' || bytes[offset + 1] != 'v' || bytes[offset + 2] != 'c'
                    || bytes[offset + 3] != 'C') {
                continue;
            }
            String codecs = String.format("avc1.%02X%02X%02X", bytes[offset + 5], bytes[offset + 6],
                    bytes[offset + 7]);
            int audioSeparator = format.codecs().indexOf(',');
            if (audioSeparator >= 0) {
                codecs += format.codecs().substring(audioSeparator);
            } else if (format.hasAudio()) {
                codecs += ",mp4a.40.2";
            }
            return new UpstreamVideo.Format(format.formatId(), format.url(), format.mimeType(), codecs,
                    format.width(), format.height(), format.fps(), format.bitrate(), format.audioSampleRate(),
                    format.contentLength(), format.hasVideo(), format.hasAudio(), format.initRange(),
                    format.indexRange(), format.trackId(), format.language(), format.label(), format.original(),
                    format.autoGenerated());
        }
        return format;
    }

    private record AudioTrackKey(String mimeType, String language, String label, Boolean original,
            boolean autoGenerated) {
    }

    private record CacheEntry(Mono<UpstreamVideo> value, long expiresAt) {
    }
}
