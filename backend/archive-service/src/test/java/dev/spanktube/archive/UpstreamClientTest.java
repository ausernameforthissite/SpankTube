package dev.spanktube.archive;

import java.net.InetSocketAddress;
import java.nio.charset.StandardCharsets;

import com.sun.net.httpserver.HttpServer;
import org.junit.jupiter.api.Test;

import static org.assertj.core.api.Assertions.assertThat;

class UpstreamClientTest {

    @Test
    void selectsOriginalAudioAndOnlyHumanSubtitles() throws Exception {
        String body = """
                {"channelId":"UC1","channelName":"Channel","title":"Video","durationSeconds":100,
                 "formats":[
                   {"formatId":"137","mimeType":"video/mp4","codecs":"avc1","width":1920,"height":1080,
                    "fps":25,"bitrate":4000000,"hasVideo":true,"hasAudio":false},
                   {"formatId":"251","mimeType":"audio/webm","codecs":"opus","bitrate":160,
                    "hasVideo":false,"hasAudio":true,"trackId":"251-en-auto","language":"en",
                    "label":"English (auto)","original":false,"autoGenerated":true},
                   {"formatId":"251","mimeType":"audio/webm","codecs":"opus","bitrate":130,
                    "hasVideo":false,"hasAudio":true,"trackId":"251-ru","language":"ru",
                    "label":"Russian","original":true,"autoGenerated":false}
                 ],
                 "subtitles":[
                   {"trackId":"sub-en","language":"en","label":"English","autoGenerated":false},
                   {"trackId":"auto-de","language":"de","label":"German (auto)","autoGenerated":true}
                 ]}
                """;
        HttpServer server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.createContext("/internal/v1/videos/test", exchange -> {
            byte[] bytes = body.getBytes(StandardCharsets.UTF_8);
            exchange.getResponseHeaders().add("Content-Type", "application/json");
            exchange.sendResponseHeaders(200, bytes.length);
            exchange.getResponseBody().write(bytes);
            exchange.close();
        });
        server.start();
        try {
            UpstreamClient client = new UpstreamClient("http://127.0.0.1:" + server.getAddress().getPort());
            UpstreamClient.VideoDownload video = client.video("test");

            UpstreamClient.Selection selection = video.select(new ArchiveModels.DownloadOptions(null, null, true, true));
            UpstreamClient.Selection legacy = video.select(new ArchiveModels.DownloadOptions(null, "251", true, true));

            assertThat(selection.audio().trackId()).isEqualTo("251-ru");
            assertThat(legacy.audio().trackId()).isEqualTo("251-ru");
            assertThat(video.subtitles()).singleElement().satisfies(track -> {
                assertThat(track.trackId()).isEqualTo("sub-en");
                assertThat(track.autoGenerated()).isFalse();
            });
        } finally {
            server.stop(0);
        }
    }

    @Test
    void returnsLiveManifestAndMetadata() throws Exception {
        String body = """
                {"streamType":"LIVE_STREAM","liveHlsUrl":"https://manifest.googlevideo.com/live.m3u8",
                 "channelId":"UC1","channelName":"Channel","title":"Live","description":"On air"}
                """;
        HttpServer server = HttpServer.create(new InetSocketAddress("127.0.0.1", 0), 0);
        server.createContext("/internal/v1/videos/live", exchange -> {
            byte[] bytes = body.getBytes(StandardCharsets.UTF_8);
            exchange.getResponseHeaders().add("Content-Type", "application/json");
            exchange.sendResponseHeaders(200, bytes.length);
            exchange.getResponseBody().write(bytes);
            exchange.close();
        });
        server.start();
        try {
            UpstreamClient.LiveSource source = new UpstreamClient("http://127.0.0.1:" + server.getAddress().getPort())
                    .liveVideo("live");

            assertThat(source.manifestUrl()).isEqualTo("/media/v/live/live.m3u8");
            assertThat(source.metadata().title()).isEqualTo("Live");
            assertThat(source.metadata().quality()).isEqualTo("LIVE_RECORDING");
        } finally {
            server.stop(0);
        }
    }
}
